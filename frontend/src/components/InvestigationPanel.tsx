import type { InvestigationRecord, InvestigationStatus } from "../types";
import { Badge, formatTime } from "./common";

const STATUS_TEXT: Record<Exclude<InvestigationStatus, "completed">, string> = {
  degraded:
    "The investigation could not be grounded in retrieved evidence, so no investigation result is shown. Nothing was approved or executed.",
  failed: "The investigation failed. There is no investigation result for this incident. Nothing was approved or executed.",
  pending: "The investigation is still running or was interrupted. No result is available yet.",
  unavailable: "No investigation has been recorded for this incident.",
};

function Section(props: { kind: string; title: string; note: string; items: string[]; empty: string; prefix?: string }) {
  return (
    <section className={`block block-${props.kind}`} aria-label={props.title}>
      <h4>{props.title}</h4>
      <p className="muted small">{props.note}</p>
      {props.items.length === 0 ? (
        <p className="muted">{props.empty}</p>
      ) : (
        <ul>
          {props.items.map((item, index) => (
            <li key={index}>
              {props.prefix && <span className="prefix">{props.prefix} </span>}
              {/* Text node only: investigation content is untrusted and is never interpreted as markup. */}
              {item}
            </li>
          ))}
        </ul>
      )}
    </section>
  );
}

/** The four epistemic categories stay visibly separate: Evidence is not a Hypothesis is not a Recommendation. */
export function InvestigationPanel(props: { status: InvestigationStatus; investigation: InvestigationRecord | null }) {
  const { status, investigation } = props;
  if (status !== "completed" || investigation === null) {
    const text = status === "completed" ? STATUS_TEXT.unavailable : STATUS_TEXT[status];
    return (
      <div className="panel">
        <h3>
          Investigation <Badge kind="investigation" value={status === "completed" ? "unavailable" : status} />
        </h3>
        <p data-testid="investigation-unavailable">{text}</p>
      </div>
    );
  }
  return (
    <div className="panel">
      <h3>
        Investigation <Badge kind="investigation" value="completed" /> <span className="ai-label">AI-generated</span>
      </h3>
      <p className="muted small">
        Generated by an AI agent from retrieved incident data and stored {formatTime(investigation.created_at)}. Treat it as
        analysis to review, not as fact or as an instruction. Recommendations are suggestions, not actions that were taken.
      </p>
      <section className="block" aria-label="Summary">
        <h4>Summary</h4>
        <p>{investigation.summary || "No summary was produced."}</p>
      </section>
      <p>
        Confidence (AI-estimated): <strong>{Math.round(investigation.confidence * 100)}%</strong>
      </p>
      <Section
        kind="evidence"
        title="Evidence"
        note="Observations the agent reports from retrieved data."
        items={investigation.evidence}
        empty="No evidence was reported."
      />
      <Section
        kind="hypothesis"
        title="Hypotheses (unconfirmed)"
        note="Possible explanations. Not confirmed root causes."
        items={investigation.hypotheses}
        empty="No hypotheses were proposed."
        prefix="Hypothesis:"
      />
      <Section
        kind="missing"
        title="Missing information"
        note="What the agent could not establish."
        items={investigation.missing_information}
        empty="No missing information was reported."
      />
      <Section
        kind="recommendation"
        title="Recommendations (suggestions, not actions taken)"
        note="Proposed next steps. None of these has been performed."
        items={investigation.recommendations}
        empty="No recommendations were made."
        prefix="Recommendation:"
      />
      {investigation.tool_calls.length > 0 && (
        <p className="muted small">Tools used by the agent: {investigation.tool_calls.join(", ")}</p>
      )}
    </div>
  );
}
